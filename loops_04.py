# For Loops

# Q1
city_names = ['Lahore', 'Karachi', 'Sialkot', 'Gawadar', ]
for city in city_names:
    print(city)

# Q2
word = 'Normal'
for w in word:
    print(w)

# Q3
person = {
    'name' : 'Shan',
    'age' : 23,
    'City' : 'Lahore'
}
for key, value in person.items():
    print(f"Key is {key} : Value is {value}")